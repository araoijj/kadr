extension Library {
    /// Tags found in the folder, most frequent first.
    var tags: [(id: String, count: Int)] {
        var c: [String: Int] = [:]
        for p in photos { for t in p.cull?.tags ?? [] { c[t, default: 0] += 1 } }
        return c.map { ($0.key, $0.value) }.sorted { $0.1 > $1.1 }
    }
}
